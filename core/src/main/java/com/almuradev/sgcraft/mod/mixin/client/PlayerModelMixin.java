package com.almuradev.sgcraft.mod.mixin.client;

import com.almuradev.sgcraft.mod.client.malp.MalpConsolePose;
import net.minecraft.client.model.player.PlayerModel;
import net.minecraft.client.renderer.entity.state.AvatarRenderState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

// Puts the arms of a player at a MALP console onto its controls, or around a MALP tablet, once the model has posed
// them its own way
@Mixin(PlayerModel.class)
abstract class PlayerModelMixin {

    @Inject(method = "setupAnim(Lnet/minecraft/client/renderer/entity/state/AvatarRenderState;)V",
            at = @At("TAIL"))
    private void sgcraft$consoleArms(final AvatarRenderState state, final CallbackInfo callback) {
        MalpConsolePose.arms((PlayerModel) (Object) this, state);
    }
}
