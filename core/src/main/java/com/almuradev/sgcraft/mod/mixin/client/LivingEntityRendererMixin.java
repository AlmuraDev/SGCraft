package com.almuradev.sgcraft.mod.mixin.client;

import com.almuradev.sgcraft.mod.entity.JumperShelter;
import com.llamalad7.mixinextras.injector.ModifyReturnValue;
import net.minecraft.client.renderer.entity.LivingEntityRenderer;
import net.minecraft.world.entity.LivingEntity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

// Players and creatures aboard a puddle jumper, seated or standing in it, show no name over them, through its hull or
// within it, however it flies
@Mixin(LivingEntityRenderer.class)
abstract class LivingEntityRendererMixin {

    @ModifyReturnValue(method = "shouldShowName(Lnet/minecraft/world/entity/LivingEntity;D)Z", at = @At("RETURN"))
    private boolean sgcraft$hideAboard(final boolean shown, final LivingEntity entity, final double distance) {
        return shown && !JumperShelter.sheltered(entity);
    }
}
