package com.almuradev.sgcraft.mod.mixin;

import com.mojang.datafixers.util.Pair;
import it.unimi.dsi.fastutil.objects.ObjectArrayList;
import net.minecraft.world.level.levelgen.structure.pools.StructurePoolElement;
import net.minecraft.world.level.levelgen.structure.pools.StructureTemplatePool;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Mutable;
import org.spongepowered.asm.mixin.gen.Accessor;

import java.util.List;

/** Lets a gate plaza join a pool, beside the pieces already in it. */
@Mixin(StructureTemplatePool.class)
public interface StructureTemplatePoolAccessor {

    @Accessor("rawTemplates")
    List<Pair<StructurePoolElement, Integer>> sgcraft$rawTemplates();

    @Mutable
    @Accessor("rawTemplates")
    void sgcraft$setRawTemplates(final List<Pair<StructurePoolElement, Integer>> templates);

    @Accessor("templates")
    ObjectArrayList<StructurePoolElement> sgcraft$templates();
}
