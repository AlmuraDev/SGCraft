package com.almuradev.sgcraft.mod.mixin.client;

import com.almuradev.sgcraft.mod.client.rings.RingHoldInput;
import net.minecraft.client.player.ClientInput;
import net.minecraft.client.player.KeyboardInput;
import net.minecraft.world.entity.player.Input;
import net.minecraft.world.phys.Vec2;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

// Stops the player's movement keys while a ring transport holds them, so they neither walk, jump, sneak nor sprint
@Mixin(KeyboardInput.class)
abstract class KeyboardInputMixin extends ClientInput {

    @Inject(method = "tick", at = @At("TAIL"))
    private void sgcraft$ringHold(final CallbackInfo callback) {
        if (RingHoldInput.held()) {
            this.keyPresses = Input.EMPTY;
            this.moveVector = Vec2.ZERO;
        }
    }
}
